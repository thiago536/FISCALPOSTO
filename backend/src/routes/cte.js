const router = require("express").Router();
const { auth } = require("../middleware/auth");
const { a } = require("../utils/rota");
const ctrl = require("../controllers/cteController");
router.get("/", auth, a(ctrl.listar));
router.get("/:id/xml", auth, a(ctrl.xml));
router.get("/:id/pdf", auth, a(ctrl.pdf));
router.post("/:id/sincronizar", auth, a(ctrl.sincronizar));
router.get("/:id", auth, a(ctrl.detalhe));
router.post("/", auth, a(ctrl.emitir));
router.post("/:id/cancelar", auth, a(ctrl.cancelar));
module.exports = router;
